import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { validateI18n } from "./i18n-validation.mjs";

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(repositoryRoot, "apps", "desktop", "src", "i18n", "coverage.generated.ts");

export function renderCoverageModule(coverage) {
  const locales = coverage
    .map(
      ({ locale, percentage, totalUnits, translatedUnits }) =>
        `  ${locale}: {\n    translatedUnits: ${translatedUnits},\n    totalUnits: ${totalUnits},\n    percentage: ${percentage},\n  },`,
    )
    .join("\n");

  return `// Generated by scripts/generate-i18n-coverage.mjs. Do not edit manually.\nexport const translationCoverage = {\n${locales}\n} as const;\n`;
}

export async function generateTranslationCoverage(root = repositoryRoot, destination = outputPath) {
  const report = await validateI18n(root);
  const generated = renderCoverageModule(report.coverage);
  const current = await readFile(destination, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });

  if (current === generated) return false;

  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, generated, "utf8");
  return true;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    await generateTranslationCoverage();
  } catch (error) {
    console.error(
      `i18n coverage generation failed: ${error instanceof Error ? error.message : String(error)}`,
    );
    process.exitCode = 1;
  }
}
